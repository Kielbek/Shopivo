package pl.shopivo.shared.error;

import java.util.Map;
import org.springframework.http.HttpStatus;

/**
 * Base class for expected business/API errors. Rendered as RFC 9457 Problem Details with a stable
 * {@code code} the frontend maps to localized messages.
 */
public class ApiException extends RuntimeException {

    private final HttpStatus status;
    private final String code;
    private final transient Map<String, Object> properties;

    public ApiException(HttpStatus status, String code, String message) {
        this(status, code, message, Map.of());
    }

    public ApiException(HttpStatus status, String code, String message, Map<String, Object> properties) {
        super(message);
        this.status = status;
        this.code = code;
        this.properties = properties;
    }

    public HttpStatus status() {
        return status;
    }

    public String code() {
        return code;
    }

    public Map<String, Object> properties() {
        return properties;
    }
}
